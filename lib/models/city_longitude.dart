/// 取城市经度：优先城市，其次所在省会；未收录返回 null。
double? longitudeOf(String province, String city) {
  if (city.isNotEmpty && city != '忽略' && kCityLongitude.containsKey(city)) {
    return kCityLongitude[city];
  }
  final capital = kProvinceCapital[province];
  if (capital != null) return kCityLongitude[capital];
  return null;
}

/// 真太阳时修正分钟数（未收录地区返回 0）。
int trueSolarMinutes(String province, String city) {
  final longitude = longitudeOf(province, city);
  if (longitude == null) return 0;
  return ((longitude - 120) * 4).round();
}
